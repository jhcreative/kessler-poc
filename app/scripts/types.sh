#!/usr/bin/env bash
# The TypeScript models come from the backend's Pydantic schemas (John: typed end to end).
#   scripts/types.sh          regenerate frontend/src/api/schema.ts
#   scripts/types.sh --check  fail if the committed types differ from what the backend says now
set -euo pipefail
cd "$(dirname "$0")/.."
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
(cd backend && .venv/bin/python -I -c "import sys; sys.path.insert(0, '.'); import runpy; runpy.run_path('tools/export_openapi.py', run_name='__main__')") > "$tmp/openapi.json"
(cd frontend && npx --no-install openapi-typescript "$tmp/openapi.json" -o "$tmp/schema.ts" >/dev/null)
{ echo "// GENERATED by app/scripts/types.sh from the backend's OpenAPI. Do not edit: change the Pydantic schemas."; cat "$tmp/schema.ts"; } > "$tmp/schema.out.ts"
if [ "${1:-}" = "--check" ]; then
  diff -q "$tmp/schema.out.ts" frontend/src/api/schema.ts >/dev/null || { echo "STOP: frontend/src/api/schema.ts is stale; run app/scripts/types.sh"; exit 1; }
  echo "types: in step with the backend"
else
  cp "$tmp/schema.out.ts" frontend/src/api/schema.ts && echo "wrote frontend/src/api/schema.ts"
fi
